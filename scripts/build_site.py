"""Generate the site's pages from the snapshot, data/ and the template's docs.

    python scripts/build_site.py --template-dir ../LabConstrictor --doc-source-dir ../LabConstrictor-docsrc
    then: zensical build --strict          (or: zensical serve)

Reads                                       Writes (git-ignored, rebuilt every time)
  build/snapshot.json (fetch_catalogue.py)    docs/apps/index.md, docs/apps/<app>/index.md
  build/media/<app>/                          docs/assets/icons/, docs/assets/shots/ (resized)
  data/site.yaml, install.yaml, ecosystem.yaml  docs/index.md, ecosystem.md, guides/install/
  content/submit.md                           docs/submit.md
  template .tools/docs + doc_source pictures  docs/guides/, docs/assets/docs-img/
  (all of the above)                          docs/llms.txt

The build never uses the network. Anything missing or inconsistent stops it with a
message naming the file to fix. The code is in scripts/lcsite/ (see its __init__.py).
"""

import argparse
import shutil
from pathlib import Path

from lcsite import guides, llms, pages_apps, pages_site
from lcsite.config import BUILD, DATA, DOCS, GENERATED, SITE_URL, SNAPSHOT, fail, load_json, load_yaml
from lcsite.images import ICON_PX, SHOT_PX, shrink


def clean() -> None:
    """Delete the pages generated by the previous run."""
    for name in GENERATED:
        path = DOCS / name
        shutil.rmtree(path) if path.is_dir() else path.unlink(missing_ok=True)


def copy_media(apps: list[dict]) -> None:
    """Resize each app's downloaded icon and screenshots into docs/assets/."""
    for app in apps:
        folder = BUILD / "media" / app["slug"]
        if app["icon"]:
            shrink(folder / app["icon"], DOCS / "assets" / "icons" / f"{app['slug']}.png", ICON_PX, square=True)
        for i, shot in enumerate(app["screenshots"], 1):
            shrink(folder / shot["file"], DOCS / "assets" / "shots" / f"{app['slug']}-{i}.jpg", SHOT_PX)


def main() -> None:
    """Build every generated page."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--template-dir", type=Path, required=True, help="checkout of the LabConstrictor template repository")
    parser.add_argument("--doc-source-dir", type=Path, required=True, help="checkout of its doc_source branch (the pictures)")
    args = parser.parse_args()
    if not SNAPSHOT.is_file():
        fail(f"no {SNAPSHOT}: run scripts/fetch_catalogue.py first")
    apps = sorted(load_json(SNAPSHOT)["apps"], key=lambda a: a["manifest"]["name"].lower())
    site, install, ecosystem = (load_yaml(DATA / f"{n}.yaml") for n in ("site", "install", "ecosystem"))
    clean()
    copy_media(apps)
    pages_site.page_home(site, apps)
    pages_apps.page_catalogue(apps)
    for app in apps:
        pages_apps.page_app(app, install["systems"])
    pages_site.page_ecosystem(ecosystem)
    pages_site.page_submit(site, f"{SITE_URL}schema/labconstrictor-app.schema.json")
    guides.build(args.template_dir, args.doc_source_dir, install["systems"], install["note"])
    llms.write(site, apps)
    print(f"Generated pages for {len(apps)} apps.")


if __name__ == "__main__":
    main()
