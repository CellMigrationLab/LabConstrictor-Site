"""Generate the site's pages from the snapshot, data/ and the template's docs.

    python scripts/build_site.py --template-dir ../LabConstrictor --doc-source-dir ../LabConstrictor-docsrc
    then: zensical build --strict          (or: zensical serve)

Reads                                       Writes (git-ignored, rebuilt every time)
  build/snapshot.json (fetch_catalogue.py)    docs/apps/index.md, docs/apps/<app>/index.md
  build/media/<app>/                          docs/assets/icons/, docs/assets/shots/ (resized)
  data/site.yaml, ecosystem.yaml  docs/index.md, ecosystem.md
  content/submit.md                           docs/submit.md
  data/demo.yaml, content/demo/               docs/demo/index.md, docs/assets/demo/
  template .tools/docs + doc_source pictures  docs/guides/, docs/assets/docs-img/, docs/assets/images/ (logo, comic)
  (all of the above)                          docs/llms.txt

The build never uses the network. Anything missing or inconsistent stops it with a
message naming the file to fix. The code is in scripts/lcsite/ (see its __init__.py).
"""

import argparse
import shutil
from pathlib import Path

from lcsite import citation, guides, hosts, hubs, llms, pages_apps, pages_demo, pages_site, projects, redirects
from lcsite.config import BUILD, DATA, DOCS, GENERATED, SITE_URL, SNAPSHOT, SNAPSHOT_FORMAT, fail, load_json, load_yaml
from lcsite.images import ICON_PX, SHOT_PX, shrink


def clean() -> None:
    """Delete the pages generated by the previous run."""
    for name in GENERATED:
        path = DOCS / name
        shutil.rmtree(path) if path.is_dir() else path.unlink(missing_ok=True)
    redirects.clean()


def copy_media(apps: list[dict]) -> None:
    """Resize each app's downloaded icon and screenshots into docs/assets/."""
    for app in apps:
        folder = BUILD / "media" / app["slug"]
        if app["icon"]:
            shrink(folder / app["icon"], DOCS / "assets" / "icons" / f"{app['slug']}.png", ICON_PX, square=True)
        for i, shot in enumerate(app["screenshots"], 1):
            shrink(folder / shot["file"], DOCS / "assets" / "shots" / f"{app['slug']}-{i}.jpg", SHOT_PX)


def copy_brand(doc_source: Path) -> None:
    """The logo (header, favicon, home page) and the comic, from the template's doc_source branch."""
    for name, dest, side, square in [("LabConstrictor_Logo.png", "logo.png", 320, True), ("LabConstrictor_Logo.png", "logo-64.png", 64, True),
                                     ("LabConstrictor_Logo.png", "favicon.png", 48, True), ("comic.png", "comic.png", 1800, False)]:
        src = doc_source / name
        if not src.is_file():
            fail(f"{src} not found: the doc_source branch should hold {name}")
        shrink(src, DOCS / "assets" / "images" / dest, side, square=square)


def load_apps() -> list[dict]:
    """The apps of build/snapshot.json, sorted by name. Stops the build when the snapshot has another format
    or no apps at all: publishing an empty App Centre because every app failed would be a silent failure."""
    snapshot = load_json(SNAPSHOT)
    if snapshot.get("format") != SNAPSHOT_FORMAT:
        fail(f"{SNAPSHOT} has format {snapshot.get('format')!r}, expected {SNAPSHOT_FORMAT}: run scripts/fetch_catalogue.py again")
    if not snapshot["apps"]:
        fail(f"{SNAPSHOT} has no apps; see build/problems.md")
    return sorted(snapshot["apps"], key=lambda a: a["manifest"]["name"].lower())


def main() -> None:
    """Build every generated page."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--template-dir", type=Path, required=True, help="checkout of the LabConstrictor template repository")
    parser.add_argument("--doc-source-dir", type=Path, required=True, help="checkout of its doc_source branch (the pictures)")
    args = parser.parse_args()
    if not SNAPSHOT.is_file():
        fail(f"no {SNAPSHOT}: run scripts/fetch_catalogue.py first")
    apps = load_apps()
    site, ecosystem = (load_yaml(DATA / f"{n}.yaml") for n in ("site", "ecosystem"))
    citation.check_template_readme(site, args.template_dir)
    clean()
    copy_media(apps)
    hosts.prepare(hosts.load())
    hosts.prepare_services()
    copy_brand(args.doc_source_dir)
    pages_site.page_home(site, apps)
    pages_apps.page_catalogue(apps)
    for app in apps:
        pages_apps.page_app(app)
    pages_site.page_ecosystem(projects.resolve(ecosystem))
    pages_demo.page_demo(apps)
    pages_site.page_submit(site, f"{SITE_URL}schema/labconstrictor-app.schema.json")
    nav = guides.build(args.template_dir, args.doc_source_dir)
    hubs.write_all(load_yaml(DATA / "hubs.yaml"), nav, args.doc_source_dir, apps)
    redirects.write_all(redirects.load())
    llms.write(site, apps)
    print(f"Generated pages for {len(apps)} apps.")


if __name__ == "__main__":
    main()
